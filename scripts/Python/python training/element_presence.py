# Check if the name if within the list
guest = ['J', 'Da']
name = input ('What is your name  ')
if name in guest:
    print('Welcome!')
else:
    print('You are not on the guest list!')


# Check if the name NOT in the list
guest = ['J', 'Da']
name = input ('What is your name  ')
if name not in guest:
    print('Welcome!')
else:
    print('You are not on the guest list!')